/**
 * 헤더 팝오버(알림 · 수신 상태)가 놓이는 자리 — **좁은 화면에서는 버튼이 아니라 화면 오른쪽
 * 여백에 붙는다** `[2026-09-30 검토: 360px에서 알림 팝오버가 왼쪽으로 16px 잘렸다]`.
 *
 * 헤더를 한 줄로 줄이며(2026-09-18) 종과 수신 점이 오른쪽 끝에서 안쪽으로 들어갔다(계정 버튼
 * 28px + 간격 12px). 그런데 팝오버는 여전히 **자기 버튼의 오른쪽 끝**에 맞춰 폭 320px을 왼쪽으로
 * 펼쳐, 360px에서 왼쪽 끝이 −16px, 375px에서 −1px이었다(실측) — `min(320px, 100vw − 2rem)`은
 * **버튼이 화면 오른쪽 끝에 있을 때만** 맞는 식이었다. 가장 흔한 안드로이드 폭이 360px이다.
 *
 * `sm` 미만은 화면에 고정해 본문과 같은 오른쪽 여백(16px)에 붙이고, 헤더 실높이(`--header-h`,
 * 셸이 잰다) 바로 아래에 둔다. `sm` 이상은 예전 그대로 버튼 아래다 — **넓은 화면은 달라지지 않는다.**
 * 계정 메뉴는 이미 맨 오른쪽 버튼이라 이 자리가 필요 없다.
 */
export const HEADER_POPOVER_PLACEMENT =
  'fixed right-4 top-[var(--header-h)] mt-1.5 sm:absolute sm:right-0 sm:top-auto';

