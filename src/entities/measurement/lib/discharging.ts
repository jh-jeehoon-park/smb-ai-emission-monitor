import { isDischargingAt } from '@/shared/lib/timeline';

/**
 * 그 표본에서 **방류 중이었나** — 원천을 한 곳에서 고른다.
 *
 * 규칙은 하나다: **서버에 닿으면 서버 값, 폴백이면 시나리오.** `useSiteSeries`가 실측일
 * 때만 `discharging`을 채우므로(폴백에서는 `null`) 그 여부가 곧 원천의 선택이다.
 *
 * ## 왜 모아 두는가
 *
 * `[사용자 지적 2026-09-15: 방류 여부를 두 원천에서 읽는다]`. 이 규칙을 `SCR-OP-011`만
 * 갖고 있었고 **현황판·유입유출 비교는 실측 중에도 시나리오를 읽었다** — 서버가 «방류
 * 중단»이라 보내는 순간에도 벽 화면은 «방류 중»이라 적을 수 있었다. 헤더가 «계측 서버
 * 수신 중»이라 말하는 동안 한 값만 내장 데이터인 것이고, 2026-09-01에 이 화면에서 이미
 * 한 번 잡힌 결함과 같은 종류다(**E3** — 산출값은 원천을 밝힌다).
 *
 * ## 판정 코드는 그대로 시나리오를 읽는다
 *
 * 이상 탐지의 방류 의심(`idle-discharge.ts`)·리본·공정도·예측 fixture는 **시연 시나리오
 * 위에 지어진 것**이다 — fixture의 유량·전류가 `isDischargingAt`에 맞춰 만들어지므로
 * (`fixtures.ts`) 그쪽만 서버로 옮기면 그림과 판정이 갈린다. 이 함수는 **«지금 방류
 * 중인가»를 화면에 적는 자리**를 위한 것이다.
 *
 * 폴백에서는 둘이 같은 값을 돌려주므로 갈림 자체가 없다.
 */
export function dischargingAt(
  siteId: string,
  live: (boolean | null)[] | null,
  index: number,
): boolean | null {
  /*
   * **없는 표본을 묻고 있다면 모름이다**(**E4**) `[검토 2026-09-15]`.
   *
   * 화면들이 «맨 끝»을 `points.length - 1`로 묻는데 첫 응답 전에는 계열이 비어 **`-1`이
   * 들어온다.** 시나리오 쪽은 그 음수를 «구간 밖»으로 읽어 **`true`를 돌려준다** — 10개소
   * 중 9곳에서 그랬다(실측). 그래서 현황판과 유입·유출 비교가 **아무것도 받기 전에
   * «방류 중»이라 단정**하고 있었다. 현황판은 바로 그 자리 위에 *"모른다. 셋째를 둘째와
   * 섞지 않는다"* 고 적어 두고 있었다.
   */
  if (index < 0) return null;

  if (live) return live[index] ?? null;
  return isDischargingAt(siteId, index);
}
